let a = 10;

let b = a++;

console.log("A - a:", a);
console.log("A - b:", b);


a = 10;

b = ++a;

console.log("B - a:", a);
console.log("B - b:", b);


a = 10;

b = a--;

console.log("C - a:", a);
console.log("C - b:", b);


a = 10;

b = --a;

console.log("D - a:", a);
console.log("D - b:", b);